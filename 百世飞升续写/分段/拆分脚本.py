def main():
    text = open(SRC, encoding='utf-8').read()
    lines = text.split('\n')
    hd = [(i,l) for i,l in enumerate(lines) if l.startswith('# 第')]

    grp, acc, gid, out = [], 0, 1, []
    for k,(i,l) in enumerate(hd):
        end = hd[k+1][0] if k+1 < len(hd) else len(lines)
        body = '\n'.join(lines[i+1:end])
        c = len(re.findall(r'[\u4e00-\u9fff]', body))
        if grp and (acc >= TARGET or len(grp) >= MAXCH):
            out.append((gid, grp, acc)); gid += 1; grp = []; acc = 0
        grp.append((k+1, l, lines[i:end])); acc += c
    if grp: out.append((gid, grp, acc))

    os.makedirs(DST, exist_ok=True)
    for gid, grp, acc in out:
        a, b = grp[0][0], grp[-1][0]
        body = []
        for n, l, blk in grp:
            body.extend(blk)
        head = (
            '# 分段%02d｜第%d—%d章\n\n' % (gid, a, b) +
            '> 所属弧：%s\n' % arc_of(a) +
            '> 汉字：%d　章数：%d\n' % (acc, len(grp)) +
            '> 修炼状态：见 `千问写作包/11_前情摘要_1-105.md`\n\n' +
            '## 本段修改要点\n\n' + NOTES.get(gid, '') + '\n\n' +
            '---\n\n## 原文\n\n'
        )
        fn = os.path.join(DST, '%02d_ch%03d-%03d.md' % (gid, a, b))
        open(fn, 'w', encoding='utf-8').write(head + '\n'.join(body).strip() + '\n')
        print('%02d  ch%03d-%03d  %2d章  %5d字  [%s]' % (gid, a, b, len(grp), acc, arc_of(a)))
    print('\n共 %d 份，已写入 %s' % (len(out), DST))

if __name__ == '__main__':
    main()